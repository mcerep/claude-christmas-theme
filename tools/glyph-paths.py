"""Generate hooks/glyph-paths.js: the outlines of the scene's tile glyphs as SVG path data.

Why
---
The scene stamps a character on every tile (~1,200 of them) with
    <text x="4.5" y="7">   styled   font: 700 6px monospace; text-anchor: middle
Drawing that much text is what pushed the scene over the desktop app's cost budget for
moving backdrops: the app's player stops a scene whose per-frame sampling averages over
5.56 ms (measured: ~6.3 ms with text glyphs, ~3.3 ms without). A filled path with the
same outline looks the same and is much cheaper to draw.

Font
----
In the app's browser engine `monospace` resolves to Menlo (checked by comparing rendered
pixels), and weight 700 picks the Menlo-Bold face of /System/Library/Fonts/Menlo.ttc.
fontTools reads its TrueType outlines (font units, y up, origin at the left edge of the
glyph on the baseline).

Placement, matching the <text> it replaces (tile coordinates, y down)
----------------------------------------------------------------------
    scale       = FONT_SIZE / unitsPerEm                 (font units -> user units)
    left edge   = ANCHOR_X - advance * scale / 2         (text-anchor: middle)
    x_tile      = left edge + scale * x_font
    y_tile      = BASELINE_Y - scale * y_font            (flip y, baseline at BASELINE_Y)

Run on macOS (it reads the system's Menlo font) with any Python 3 that has fontTools
(pip install fonttools), from the repository's top folder:
    python3 tools/glyph-paths.py > hooks/glyph-paths.js
"""

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTCollection

FONT_FILE = '/System/Library/Fonts/Menlo.ttc'
FACE = 'Menlo-Bold'  # PostScript name: monospace at weight 700
FONT_SIZE = 6.0  # the scene's font size, SVG user units
ANCHOR_X = 4.5  # the <text> x (text-anchor: middle)
BASELINE_Y = 7.0  # the <text> y (the baseline)
GLYPHS = ['$', 't', '%', 'X', '*', '+', ':']  # GLYPHS and FLAKE_GLYPHS in scene.js
DECIMALS = 3  # path coordinates are rounded to this many places


def number(value):
    """Round to DECIMALS places, dropping trailing zeros, for compact path data."""
    text = f'{value:.{DECIMALS}f}'.rstrip('0').rstrip('.')
    return '0' if text in ('-0', '') else text


collection = TTCollection(FONT_FILE)
# The collection holds every Menlo face; pick the bold one by its PostScript name (nameID 6).
font = next(face for face in collection.fonts if face['name'].getDebugName(6) == FACE)

scale = FONT_SIZE / font['head'].unitsPerEm  # font units -> user units
cmap = font.getBestCmap()  # Unicode code point -> glyph name
glyph_set = font.getGlyphSet()
advances = font['hmtx']  # glyph name -> (advance width, left side bearing), font units

entries = []
for ch in GLYPHS:
    name = cmap[ord(ch)]
    advance = advances[name][0] * scale
    left = ANCHOR_X - advance / 2
    svg_pen = SVGPathPen(glyph_set, ntos=number)
    # Affine (xx, xy, yx, yy, dx, dy): x' = scale*x + left,  y' = -scale*y + BASELINE_Y
    pen = TransformPen(svg_pen, (scale, 0, 0, -scale, left, BASELINE_Y))
    glyph_set[name].draw(pen)
    entries.append(f"  '{ch}': '{svg_pen.getCommands()}',")

print(f"""// GENERATED by tools/glyph-paths.py; do not edit by hand. Rerun it to regenerate.
//
// The outline of each tile glyph in {FACE} at {number(FONT_SIZE)} units, placed as the scene's
// <text x="{number(ANCHOR_X)}" y="{number(BASELINE_Y)}" text-anchor="middle"> would place it, in tile
// coordinates (one tile is 9 x 9 user units, y pointing down).
export const GLYPH_PATHS = {{
{chr(10).join(entries)}
}}""")
